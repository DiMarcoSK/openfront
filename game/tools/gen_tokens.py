#!/usr/bin/env python3
"""Generates include/contracts/tokens.h from tokens.json (W3C DTCG).

Wired via `make regen`; never edited by hand (constitution 1). The header
is an integer palette for the 4bpp VRAM layout; the hex string stays in the
file only for auditability. No colour literal is allowed outside this file."""
import json
import re
from pathlib import Path

CASE_DIR_NAME = "nintendo-ds-strategy-tycoon-incremental"


def c_name(name):
    return re.sub(r"[^0-9A-Za-z]+", "_", name).strip("_").upper()


def nds565(hex_str):
    """Convert an sRGB hex color to the 15-bit NDS BGR used by VRAM."""
    hex_str = hex_str.lstrip("#")
    r = int(hex_str[0:2], 16)
    g = int(hex_str[2:4], 16)
    b = int(hex_str[4:6], 16)
    # Numbers measure 24-bit depth; NDS uses the top 5 bits of each channel.
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)


def main():
    root = Path(__file__).resolve().parent.parent
    srcs = [
        root.parent / "cases" / CASE_DIR_NAME / "tokens.json",
        root / "data" / "tokens.json",
    ]
    src = next((s for s in srcs if s.exists()), None)
    if src is None:
        raise SystemExit("gen_tokens: tokens.json not found")
    data = json.loads(src.read_text())

    colors = {}
    for key, entry in (data.get("color") or {}).items():
        val = (entry.get("$value") or {}).get("hex")
        if val:
            colors[c_name(key)] = nds565(val)
    if not colors:
        raise SystemExit("gen_tokens: no colors in %s" % src)

    dims = {}
    for group in ("space", "radius"):
        for key, entry in (data.get(group) or {}).items():
            val = (entry.get("$value") or {})
            if isinstance(val, dict):
                dims[f"{group.upper()}.{c_name(key)}"] = val.get("value")
    motion = {}
    for key, entry in (data.get("motion") or {}).items():
        val = (entry.get("$value") or {})
        if isinstance(val, dict):
            motion[f"MOTION.{c_name(key)}"] = val.get("value")

    lines = [
        "/* tokens.h v1 - generated by tools/gen_tokens.py; DO NOT EDIT.",
        " * Source: %s (W3C DTCG). Banned list applies: no hex colour literal"
        % src.name,
        " * outside this header (constitution 1, B02 acceptance).",
        " */",
        "#ifndef WAR_TABLE_TOKENS_H_V1",
        "#define WAR_TABLE_TOKENS_H_V1",
        "",
        "#include <stdint.h>",
        "",
        "/* 15-bit NDS BGR, ready for VRAM palette banks */",
    ]
    for k, v in sorted(colors.items()):
        lines.append("#define TOKEN_COLOR_%s 0x%04xu" % (k, v))
    for k, v in sorted(dims.items()):
        if v is None:
            continue
        lines.append("#define TOKEN_%s %s" % (k.upper().replace(".", "_"), v))
    for k, v in sorted(motion.items()):
        if v is None:
            continue
        lines.append("#define TOKEN_%s %s" % (k.upper().replace(".", "_"), v))
    lines += [
        "",
        "#define TOKEN_COUNT %du" % len(colors),
        "",
        "#endif /* WAR_TABLE_TOKENS_H_V1 */",
        "",
    ]
    out = root / "include" / "contracts" / "tokens.h"
    out.write_text("\n".join(lines))
    print("tokens.h: %d colors written" % len(colors))


if __name__ == "__main__":
    main()
