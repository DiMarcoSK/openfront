ORDER = [chr(c) for c in range(32, 127)]


def glyph(ch):
    rows = G.get(ch, G["?"]).split()
    return [[r[i] == "1" for i in range(5)] for r in rows]


def text(cv, x, y, s, color, shadow=None, advance=6):
    """Draw 5x7 text; optional 1 px drop shadow (ink on enamel)."""
    for ch in s:
        g = glyph(ch)
        for gy, row in enumerate(g):
            for gx, on in enumerate(row):
                if on:
                    if shadow is not None:
                        cv.put(x + gx + 1, y + gy + 1, shadow)
                    cv.put(x + gx, y + gy, color)
        x += advance
    return x


def width(s, advance=6):
    return len(s) * advance - 1


def sheet(ink, paper=None) -> Canvas:
    """95 glyphs in 8x8 cells, 16 per row: the DS font tileset."""
    cv = Canvas(128, 48, fill=paper)
    for i, ch in enumerate(ORDER):
        text(cv, (i % 16) * 8 + 1, (i // 16) * 8, ch, ink)
    return cv


def display(cv, x, y, s, ramp4, outline, scale=2, advance=12, stencil=True):
    """Engraved bronze plate type: doubled skeleton, bevel, stencil break."""
    w = advance * len(s) + 4
    h = 7 * scale + 4
    m = np.zeros((cv.h, cv.w), bool)
    cx = x
    for ch in s:
        for gy, row in enumerate(glyph(ch)):
            for gx, on in enumerate(row):
                if on:
                    y0, x0 = y + gy * scale, cx + gx * scale
                    m[max(0, y0):y0 + scale, max(0, x0):x0 + scale] = True
        cx += advance
    if stencil:
        mid = y + 3 * scale + scale // 2
        m[mid, :] &= False
    cv.fill(dilate(m, True) & ~m, outline)
    cv.fill(m, ramp4[1])
    top = m & ~np.roll(m, 1, axis=0)
    left = m & ~np.roll(m, 1, axis=1)
    bot = m & ~np.roll(m, -1, axis=0)
    cv.fill(bot, ramp4[0])
    cv.fill(top | left, ramp4[2])
    cv.fill(top & left, ramp4[3])
    return cx
